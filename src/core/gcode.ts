import type { GenStats, Op, PrintSettings, Vec3 } from './types';

const f = (v: number) => {
  const s = v.toFixed(3);
  return s.replace(/\.?0+$/, '') || '0';
};

export function formatDuration(seconds: number): string {
  const s = Math.max(0, Math.round(seconds));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  if (h > 0) return `${h}h ${m}m`;
  return `${m}m ${s % 60}s`;
}

export interface GcodeOutput {
  gcode: string;
  stats: GenStats;
}

export function writeGcode(
  ops: Op[],
  print: PrintSettings,
  name: string,
  start: Vec3 | null,
): GcodeOutput {
  const area = Math.PI * Math.pow(print.filamentDiameter / 2, 2);
  const lines: string[] = [];
  const travelFeed = Math.round(print.travelSpeed * 60);
  const printFeed = Math.round(print.printSpeed * 60);
  const startPoint = start ?? { x: print.bedX / 2, y: print.bedY / 2, z: print.layerHeight };

  lines.push('; ------------------------------------------------------------');
  lines.push('; Generated by HELIX Studio · parametric G-code generator');
  lines.push(`; Model: ${name}`);
  lines.push(`; Layer height: ${print.layerHeight} mm | Line width: ${print.lineWidth} mm`);
  lines.push(`; Bed: ${print.bedX} x ${print.bedY} mm | Filament: ${print.filamentDiameter} mm`);
  lines.push('; ------------------------------------------------------------');
  lines.push('G21 ; millimeters');
  lines.push('G90 ; absolute positioning');
  lines.push('M83 ; relative extrusion');
  if (print.bedTemp > 0) lines.push(`M140 S${print.bedTemp} ; bed target`);
  if (print.nozzleTemp > 0) lines.push(`M104 S${print.nozzleTemp} ; nozzle target`);
  if (print.bedTemp > 0) lines.push('M190 ; wait for bed');
  if (print.nozzleTemp > 0) lines.push('M109 ; wait for nozzle');
  lines.push('G28 ; home all axes');
  lines.push('G92 E0');
  lines.push('G1 Z5 F600');
  lines.push(
    `G1 X${f(startPoint.x)} Y${f(startPoint.y)} F${travelFeed} ; move to start`,
  );
  lines.push(`G1 Z${f(startPoint.z)} F600`);
  lines.push('M106 S255 ; part cooling fan on');
  lines.push('; ---------------- toolpath ----------------');

  let extrudeLen = 0;
  let travelLen = 0;
  let volume = 0;
  let lastZ = startPoint.z;
  let lastFeed = 0;
  let maxLayer = 0;

  for (const op of ops) {
    const dx = op.x1 - op.x0;
    const dy = op.y1 - op.y0;
    const dz = op.z1 - op.z0;
    const len = Math.hypot(dx, dy, dz);
    if (op.type === 'travel') {
      travelLen += len;
      if (Math.abs(dx) < 1e-4 && Math.abs(dy) < 1e-4 && Math.abs(dz) > 1e-4) {
        lines.push(`G1 Z${f(op.z1)} F600 ; layer up`);
        lastZ = op.z1;
      } else {
        let line = `G1 X${f(op.x1)} Y${f(op.y1)}`;
        if (Math.abs(op.z1 - lastZ) > 1e-4) {
          line += ` Z${f(op.z1)}`;
          lastZ = op.z1;
        }
        line += ` F${travelFeed}`;
        lines.push(line);
        lastFeed = travelFeed;
      }
      continue;
    }

    extrudeLen += len;
    volume += len * op.width * print.layerHeight;
    maxLayer = Math.max(maxLayer, op.layer);
    let line = `G1 X${f(op.x1)} Y${f(op.y1)}`;
    if (Math.abs(op.z1 - lastZ) > 1e-4) {
      line += ` Z${f(op.z1)}`;
      lastZ = op.z1;
    }
    line += ` E${f((len * op.width * print.layerHeight) / area)}`;
    if (printFeed !== lastFeed) {
      line += ` F${printFeed}`;
      lastFeed = printFeed;
    }
    lines.push(line);
  }

  const filamentLength = volume / area;
  const mass = (volume / 1000) * 1.24;
  const seconds = 60 + extrudeLen / Math.max(1, print.printSpeed) + travelLen / Math.max(1, print.travelSpeed);

  lines.push('; ---------------- end ----------------');
  lines.push('M107 ; fan off');
  lines.push('M104 S0 ; nozzle off');
  lines.push('M140 S0 ; bed off');
  lines.push('G91 ; relative positioning');
  lines.push('G1 Z10 F600 ; lift');
  lines.push('G90 ; absolute positioning');
  lines.push('G28 X0 Y0 ; park');
  lines.push('M84 ; motors off');
  lines.push(`; extrusion length: ${(extrudeLen / 1000).toFixed(2)} m`);
  lines.push(`; filament: ${(filamentLength / 1000).toFixed(2)} m / ${mass.toFixed(2)} g`);
  lines.push(`; estimated time: ${formatDuration(seconds)}`);
  lines.push('; ------------------------------------------------------------');

  const stats: GenStats = {
    extrusionLength: extrudeLen,
    travelLength: travelLen,
    volume,
    filamentLength,
    filamentMass: mass,
    timeSeconds: seconds,
    layers: maxLayer + 1,
    lineCount: lines.length,
  };

  return { gcode: lines.join('\n'), stats };
}
